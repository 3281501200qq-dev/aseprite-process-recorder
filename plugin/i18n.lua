local language = "zh_CN"

function I18n.normalize(value)
  return translations[value] and value or "zh_CN"
end

function I18n.setLanguage(value)
  language = I18n.normalize(value)
  return language
end

function I18n.language()
  return language
end

function I18n.text(key)
  return translations[language][key] or translations.zh_CN[key] or key
end

return I18n
